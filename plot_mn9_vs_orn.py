def run_for_mn9(args: argparse.Namespace, mn9_key: str) -> None:
    df_rate, df_std, exp_info = load_experiment_rates(args.experiments_dir, args.hz)
    ctrl_mean, ctrl_sd = get_control_stats(df_rate, df_std, args.hz, mn9_key)

    # Extract ORN cell types from exp_info
    orn_cells = sorted({cell for cell, _, _ in exp_info})
    if len(orn_cells) == 1:
        orn_tag = orn_cells[0]
    else:
        orn_tag = "mixed"

    # Slugify to make filename-safe
    orn_tag = re.sub(r"[^A-Za-z0-9]+", "_", orn_tag).strip("_").lower()

    out_file = args.output_dir / f"{orn_tag}_{args.hz}Hz.png"

    make_plot(
        df_rate,
        df_std,
        exp_info,
        ctrl_mean,
        ctrl_sd,
        args.hz,
        mn9_key,
        out_file,
    )
    print(f"Saved plot → {out_file}")


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    if args.mn9 == "both":
        run_for_mn9(args, "MN9_LEFT")
        run_for_mn9(args, "MN9_RIGHT")
    else:
        run_for_mn9(args, args.mn9)


if __name__ == "__main__":
    main()