#!/usr/bin/env python3
"""
plot_mn9_vs_orn.py

Scatter + error-bar panels of MN9 firing rate vs ORN frequency.

Expect directory layout:
    grn_sweeps/                 ← --experiments-dir (default)
        ├── grn_sweeps_45Hz/    ← auto-selected when --hz=45
        │     ├─ filtered_rates_45Hz_*.csv
        │     └─ filtered_rates_std_45Hz_*.csv
        ├── grn_sweeps_55Hz/
        └── …

The script reads those summary CSVs (generated by `summarize_rates.py`),
derives the control baseline from `sugar_only_<Hz>Hz` columns, and produces
PNG plots in --output-dir.
"""

from __future__ import annotations

import argparse
import re
import warnings
from pathlib import Path
from typing import List, Tuple

import matplotlib.pyplot as plt
import pandas as pd

from constants import CELL_LOOKUP

_MN9_ALIASES = {
    "1": "MN9_LEFT",
    "left": "MN9_LEFT",
    "mn9_left": "MN9_LEFT",
    "l": "MN9_LEFT",
    "2": "MN9_RIGHT",
    "right": "MN9_RIGHT",
    "mn9_right": "MN9_RIGHT",
    "r": "MN9_RIGHT",
}

def to_mn9_key(user_in: str) -> str:
    """Return canonical 'MN9_LEFT' or 'MN9_RIGHT' (or raise)."""
    key = user_in.strip().lower()
    if key == "both":
        return "both"
    canonical = _MN9_ALIASES.get(key, key.upper())
    if canonical not in ("MN9_LEFT", "MN9_RIGHT"):
        raise argparse.ArgumentTypeError(
            f"Unrecognised MN9 selector '{user_in}'. "
            "Use 1/2, left/right, MN9_LEFT/MN9_RIGHT, or both."
        )
    return canonical


# ────────────────────────────────────────────────────────────────────────────
# CLI
# ────────────────────────────────────────────────────────────────────────────
def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Plot MN9 firing-rate vs ORN-frequency panels "
                    "from summarize_rates CSV outputs"
    )
    p.add_argument(
        "-e", "--experiments-dir",
        type=Path,
        default=Path("./grn_sweeps"),
        help="Root directory containing *grn_sweeps_<Hz>Hz* sub-folders.",
    )
    p.add_argument(
        "-o", "--output-dir",
        type=Path,
        default=Path("./mn9_vs_orn_plots"),
        help="Directory in which to save PNG plots.",
    )
    p.add_argument(
        "--hz",
        type=int,
        required=True,
        help="Sugar stimulation frequency (Hz).",
    )
    p.add_argument(
        "--mn9",
        type=to_mn9_key,  # ← convert immediately
        default="MN9_LEFT",
        help=('Which MN9 neuron to plot: 1, 2, left, right, '
              'MN9_LEFT, MN9_RIGHT, or both (default: MN9_LEFT).'),
    )
    return p.parse_args()


