def resolve_hz_dir(root: Path, hz: int) -> Path:
    """Return the directory that holds CSVs for the requested Hz."""
    hz_suffix = f"{hz}Hz"

    if root.name.endswith(hz_suffix):
        return root

    matches = [d for d in root.iterdir() if d.is_dir() and d.name.endswith(hz_suffix)]
    if not matches:
        raise FileNotFoundError(
            f"No subdirectory ending with '{hz_suffix}' found beneath {root}"
        )
    if len(matches) > 1:
        raise RuntimeError(
            f"Multiple subdirectories ending with '{hz_suffix}' found under {root}: "
            f"{[m.name for m in matches]} – please disambiguate."
        )
    return matches[0]


def discover_summary_csvs(hz_dir: Path, hz: int) -> Tuple[List[Path], List[Path]]:
    """Locate filtered-rates CSV pairs for the requested sugar Hz."""
    rate_files = list(hz_dir.glob(f"filtered_rates_{hz}Hz_*.csv"))
    std_files = list(hz_dir.glob(f"filtered_rates_std_{hz}Hz_*.csv"))

    if not rate_files:
        raise FileNotFoundError(f"No filtered_rates_{hz}Hz_*.csv found in {hz_dir}")
    if not std_files:
        warnings.warn(
            f"No filtered_rates_std_{hz}Hz_*.csv found in {hz_dir}; "
            "error bars will be suppressed."
        )
    return rate_files, std_files


def load_experiment_rates(
    root: Path, hz: int
) -> Tuple[pd.DataFrame, pd.DataFrame, List[Tuple[str, int, str]]]:
    """
    Merge all summary CSVs and extract (cell_type, ORN_Hz, col_name) metadata.
    """
    hz_dir = resolve_hz_dir(root, hz)
    rate_csvs, std_csvs = discover_summary_csvs(hz_dir, hz)

    # Concatenate rate tables
    df_rate = pd.concat((pd.read_csv(f).set_index("name") for f in rate_csvs), axis=1)

    # Concatenate std tables (or zeros if absent)
    if std_csvs:
        df_std = pd.concat((pd.read_csv(f).set_index("name") for f in std_csvs), axis=1)
    else:
        df_std = pd.DataFrame(index=df_rate.index, columns=df_rate.columns).fillna(0.0)

    # Remove duplicated columns that can appear when multiple CSVs share experiments
    df_rate = df_rate.loc[:, ~df_rate.columns.duplicated()]
    df_std = df_std.loc[:, ~df_std.columns.duplicated()]

    # Experiment metadata from column names
    # ── recognise “…/sugar45Hz_plus_<CELL>_<FREQ>Hz”
    pattern = re.compile(
        rf"sugar{hz}Hz_plus_(?P<cell>.+)_(?P<freq>\d+)Hz$",  # allow “_” inside <cell>
        re.I,
    )

    exp_info: list[tuple[str, int, str]] = []
    for col in df_rate.columns:
        base = col.split("/")[-1]  # drop “experiments/” or “controls/” prefix
        m = pattern.match(base)
        if not m:
            continue  # probably a control column
        exp_info.append((m.group("cell"), int(m.group("freq")), col))

    if not exp_info:
        raise RuntimeError("No experiment columns recognised after parsing.")

    return df_rate, df_std, exp_info


def get_control_stats(
    df_rate: pd.DataFrame, df_std: pd.DataFrame, hz: int, mn9_label: str
) -> Tuple[float, float]:
    """
    Derive control mean ± SD from 'sugar_only_<Hz>Hz' columns.
    If multiple control replicates exist, mean is across replicates and
    SD is their sample standard deviation; otherwise SD falls back to
    the per-run SD stored in df_std.
    """
    pattern = re.compile(rf"sugar_only_{hz}Hz", re.I)
    control_cols = [c for c in df_rate.columns if pattern.search(c)]

    if not control_cols:
        raise RuntimeError(
            f"No control columns matching 'sugar_only_{hz}Hz' found in rate CSVs."
        )

    values = df_rate.loc[mn9_label, control_cols].astype(float)
    mean = float(values.mean())

    if len(control_cols) > 1:
        sd = float(values.std(ddof=0))
    else:
        sd = float(df_std.loc[mn9_label, control_cols[0]])

    return mean, sd


def make_plot(
    df_rate: pd.DataFrame,
    df_std: pd.DataFrame,
    exp_info: List[Tuple[str, int, str]],
    ctrl_mean: float,
    ctrl_sd: float,
    hz: int,
    mn9_label: str,
    out_path: Path,
) -> None:
    """Generate and save a single MN9-vs-ORN plot."""
    cells = sorted({cell for cell, _, _ in exp_info})
    orn_vals = sorted({orn for _, orn, _ in exp_info})
    xmin, xmax = min(orn_vals), max(orn_vals)

    plt.figure(figsize=(8, 6))

    for cell in cells:
        pts = sorted(
            [
                (
                    orn,
                    df_rate.at[mn9_label, col],
                    df_std.at[mn9_label, col],
                    col,  # include column name for annotation
                )
                for c, orn, col in exp_info
                if c == cell
            ],
            key=lambda x: x[0],
        )
        xs, ys, errs, labels = zip(*pts)
        plt.errorbar(xs, ys, yerr=errs, fmt="o-", label=cell)

        # Add small text annotations
        for x, y, label in zip(xs, ys, labels):
            lbl = label.split("_plus_")[-1]  # get <CELL>_<FREQ>Hz
            plt.annotate(lbl, (x, y), textcoords="offset points",
                         xytext=(5, 5), ha='left', fontsize=7, alpha=0.75)

    plt.xlabel("ORN frequency (Hz)")
    plt.ylabel(f"{mn9_label} rate (Hz)")
    plt.title(f"{mn9_label} firing rate vs ORN frequency (sugar {hz} Hz)")
    plt.legend(fontsize="small")
    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    plt.close()


